export function stickerAliasTags(text, joinedName = false) {
  return aliases.filter(([pattern]) => new RegExp(joinedName ? pattern : pattern.replace(/\b(cat|dog|tea|sun|moon|wave|yes|bed|home)\b/g, '\\b$1\\b'), 'i').test(text))
    .flatMap(([, words]) => words.split(' '));
}

export function categorizeSticker(text, joinedName = false) {
  const matches = stickerCategories.filter(c => {
    // Natural English keywords need boundaries for short ambiguous words. Reaction
    // filenames deliberately join words (blobcatcoffee), so keep substring matching.
    const pattern = joinedName ? c.pattern : c.pattern.replace(/\b(cat|dog|car|tea|pen|egg|cup|sun|hot|bag|card|hat|star|rain|nom|yum|code|wave|yes|nod|pat|care|love|gift|work|book|home|bed)\b/g, '\\b$1\\b');
    return c.id !== 'misc' && new RegExp(pattern, 'i').test(text);
  });
  return matches.length ? matches : [stickerCategories.at(-1)];
}

