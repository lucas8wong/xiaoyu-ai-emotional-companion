/**
 * 取当前界面语言的文案。
 * 与主 App 的 `t()` 同语义：占位符写成 `{name}`，未收录的 key 原样返回（便于发现漏翻）。
 */
export function wwT(key: string, vars?: Record<string, string | number>): string {
  const lang = getLang();
  const dict = DICTS[lang] || ZH;
  let text = dict[key] ?? ZH[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.split(`{${k}}`).join(String(v));
    }
  }
  return text;
}

/** 身份名 */
export function roleName(role: string): string {
  const map: Record<string, string> = {
    werewolf: 'roleWerewolf',
    seer: 'roleSeer',
    witch: 'roleWitch',
    hunter: 'roleHunter',
    villager: 'roleVillager',
  };
  return wwT(map[role] || 'roleVillager');
}

